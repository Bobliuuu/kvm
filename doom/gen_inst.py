#!/usr/bin/env python3
"""Generate include/kvm_doom_inst.inc: the per-instance symbol prefixes, declarations and the dispatch switch for up to MAX engine instances
(doom/build.sh DOOM_INSTANCES=N builds doom_dev_i<k>.o with every symbol prefixed i<k>_).   gen_inst.py [MAX=64] > include/kvm_doom_inst.inc"""
import sys
MAX = int(sys.argv[1]) if len(sys.argv) > 1 else 64
FUNCS = ["void gpu_doom_boot(const unsigned char* wad, long wad_len)", "void gpu_doom_tic(uint32_t input)", "void gpu_doom_worker(int tid)",
         "void gpu_doom_abort_tic()", "void doom_state(int32_t* out)", "void gpu_doom_sim(uint32_t input)", "void gpu_doom_draw(int tile, int ntiles, int tid, int nthreads)",
         "void gpu_doom_post()", "int gpu_doom_pending()", "int gpu_doom_log_tic()"]
print(f"// GENERATED by doom/gen_inst.py {MAX}: do not edit. Included by kvm_ops_game.cuh.")
print(f"#define KVM_DOOM_MAX_INSTANCES {MAX}")
print("#define KVM_DOOM_PFX_0")
for k in range(1, MAX):
    print(f"#define KVM_DOOM_PFX_{k} i{k}_")
print("#define KVM_DOOM_DECL(k) extern \"C\" { \\")
for f in FUNCS:
    ret, rest = f.split(" ", 1)
    name, args = rest.split("(", 1)
    print(f"  __device__ {ret} KVM_DOOM_SYM(k, {name})({args}; \\")
print("  extern __device__ unsigned char* KVM_DOOM_SYM(k, I_VideoBuffer); extern __device__ uint32_t KVM_DOOM_SYM(k, colors)[256]; }")
for k in range(1, MAX):
    print(f"KVM_DOOM_DECL({k})")
print("#define KVM_DOOM_ARM(k, M) case k: if constexpr (KVM_DOOM_INSTANCES > k) { M(k) } break;")
print("#define KVM_DOOM_SWITCH(inst, M) switch (inst) { \\")
for k in range(MAX):
    print(f"  KVM_DOOM_ARM({k}, M) \\")
print("  default: break; }")
