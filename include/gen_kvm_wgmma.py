#!/usr/bin/env python3
"""Generate include/kvm_wgmma.inc: inline-PTX wrappers for the sm_90a wgmma shapes the Hopper GEMM tiles use.

  python3 include/gen_kvm_wgmma.py > include/kvm_wgmma.inc

Each wrapper issues one wgmma.mma_async with fp32 accumulators held in a float array (the register layout of PTX ISA "wgmma D
fragment": thread t of the warpgroup owns rows 16*(t/32) + (t%32)/4 (+8) and columns 8j + 2*(t%4) (+1) of every n8 block j).
scale-d is always 1 (the caller zeroes the accumulators), scale-a = scale-b = 1. bf16 wrappers take the transpose bits as template
arguments (0 = K-major, 1 = MN-major); tf32 has no transpose form, both operands must be K-major.
"""
SHAPES = [('tf32', 8, 32), ('tf32', 8, 64), ('tf32', 8, 128), ('bf16', 16, 256)]


def wrapper(ty, k, n):
    nacc = n // 2
    regs = ', '.join(f'%{i}' for i in range(nacc))
    a, b, sd = nacc, nacc + 1, nacc + 2
    outs = ', '.join(f'"+f"(d[{i}])' for i in range(nacc))
    if ty == 'tf32':
        head, name = 'template <int UNUSED = 0>\n', f'wgmma_m64n{n}k{k}_tf32'
        instr, tail, extra = f'wgmma.mma_async.sync.aligned.m64n{n}k{k}.f32.tf32.tf32', '1, 1', ''
    else:
        head, name = 'template <int TA, int TB>\n', f'wgmma_m64n{n}k{k}_bf16'
        instr, tail, extra = f'wgmma.mma_async.sync.aligned.m64n{n}k{k}.f32.bf16.bf16', f'1, 1, %{sd + 1}, %{sd + 2}', ', "n"(TA), "n"(TB)'
    return (f'{head}KVM_HOP_DEVI void {name}(float (&d)[{nacc}], uint64_t da, uint64_t db) {{\n'
            f'    asm volatile("{{\\n.reg .pred p;\\nsetp.ne.b32 p, %{sd}, 0;\\n{instr} {{{regs}}}, %{a}, %{b}, p, {tail};\\n}}\\n"\n'
            f'                 : {outs}\n'
            f'                 : "l"(da), "l"(db), "r"(1){extra});\n}}\n')


if __name__ == '__main__':
    print('// GENERATED by include/gen_kvm_wgmma.py: do not edit. Included by kvm_hopper.cuh inside its sm_90a guard.')
    for s in SHAPES:
        print(wrapper(*s))
