#pragma once
// Device side of the game operators in kvm_ops_game.def: the REAL Doom engine (doomgeneric, built by doom/build.sh into
// doom/build/doom_dev.o) running as ordinary scheduler tasks.
//
// ===================== EXECUTOR REQUIREMENTS (read by agent B / whoever builds the dispatcher) =====================
//  1. blockDim.x >= 256 (the engine uses exactly threads 0..255 of the CTA: thread 0 is the game thread, 1..255 draw columns/spans
//     behind named barrier 2; barrier 0 stays free for __syncthreads). Every thread of the CTA must call the op (block-cooperative).
//  2. Link: nvcc -rdc=true <your.cu> doom/build/doom_dev.o (the engine is a relocatable device object; its globals are device-global,
//     so there is exactly ONE Doom instance per process). Build it with doom/build.sh (ARCH=sm_80 default).
//  3. Stack: the engine recurses (BSP walk); cudaDeviceSetLimit(cudaLimitStackSize, KVM_DOOM_STACK_BYTES) before the launch.
//     kvm_doom_host_init() does this and uploads the WAD. The limit is per resident thread, so it costs
//     SMs * threads/SM * KVM_DOOM_STACK_BYTES of device memory.
//  4. ONE doom_tick in flight at a time, in order: tick f+1 depends on tick f (chain with DAG edges). doom_present(f)/doom_status(f)
//     read the screen of the LAST completed tick, so they must be ordered after tick f and before tick f+1 (edges both ways, or
//     present f -> tick f+1). The ops check state tic == frame+1 and fail loudly (KVM_ERR_USER) when ordering is violated.
//  5. Cross-CTA visibility is the executor's contract (release at publish / acquire at pop, fence after the op): this file only uses
//     __ldcg for data other CTAs wrote, and plain stores for what it produces.
//  6. Needs no more than the generic arguments: buffers are f32 table entries; ops reinterpret words. Scheduling: the 35 Hz pacing is
//     deadline metadata only (deadline_us on the task, doom/make_workload.py); the scheduler needs no knowledge of Doom.
//  7. A tick takes milliseconds on one CTA (serial game logic), far longer than a GEMM tile: the CTA is occupied for that time.
//
// ===================== buffer layouts (32-bit words) =====================
//  input : word 0 = KVM_DOOM_INPUT_MAGIC, word 1+f = input for tic f: bits 0..7 forwardmove (int8), 8..15 sidemove (int8),
//          16..23 turn (int8, x32 = angleturn), 24..31 buttons (BT_ATTACK=1, BT_USE=2). 0xFFFFFFFF = scripted player for that tic.
//          Without the magic (a zero-filled buffer, or f beyond its size) the scripted player plays: no cheats, the demo plays itself.
//  state : [0] booted [1] tics run [2] gamestate (0 level, 1 intermission) [3] health [4] armor [5] kills [6] monsters [7] items
//          [8] secrets [9] deaths [10] tic the level finished (-1) [11] x [12] y [13] route waypoint, [14..15] reserved,
//          then KVM_DOOM_ST_REC (16) words per frame from KVM_DOOM_ST_HASH, written by doom_status(f): [0] sum, [1] xor of the frame
//          fingerprint (doom/glue/frame_hash.h), [2..15] a copy of header words 0..13 as of tic f (the per-frame game state).
//  fb    : >= KVM_DOOM_FB_WORDS words = 64000 bytes of palette indices (row-major 320x200) + 256 RGBA/XRGB palette words at word 16000.
#include <cstdint>
#include <cstdio>
#include <vector>
#include <cuda_runtime.h>
#include "../doom/glue/frame_hash.h"

#define KVM_DOOM_INPUT_MAGIC 0x4B444D49u
#define KVM_DOOM_INPUT_SCRIPTED 0xFFFFFFFFu
#define KVM_DOOM_FB_BYTES (DOOM_PIXELS + 1024)
#define KVM_DOOM_FB_WORDS (KVM_DOOM_FB_BYTES / 4)
#define KVM_DOOM_PAL_WORD (DOOM_PIXELS / 4)
#define KVM_DOOM_ST_HEADER 16
#define KVM_DOOM_ST_BOOTED 0
#define KVM_DOOM_ST_TICS 1
#define KVM_DOOM_ST_HASH KVM_DOOM_ST_HEADER
#define KVM_DOOM_ST_REC 16
#define KVM_DOOM_STATE_WORDS(frames) (KVM_DOOM_ST_HEADER + KVM_DOOM_ST_REC * (frames))
#define KVM_DOOM_THREADS 256
#define KVM_DOOM_STACK_BYTES (16 * 1024)

extern "C" {
__device__ void gpu_doom_boot(const unsigned char* wad, long wad_len);
__device__ void gpu_doom_tic(uint32_t input);
__device__ void gpu_doom_worker(int tid);
__device__ void gpu_doom_abort_tic();
__device__ void doom_state(int32_t* out);
__device__ void gpu_doom_sim(uint32_t input);
__device__ void gpu_doom_draw(int tile, int ntiles, int tid, int nthreads);
__device__ void gpu_doom_post();
__device__ int gpu_doom_pending();
__device__ int gpu_doom_log_tic();
extern __device__ unsigned char* I_VideoBuffer;
extern __device__ uint32_t colors[256];
extern __device__ char doom_log[1 << 16];
extern __device__ volatile long doom_log_n;
}

// ---- instances. KVM_DOOM_INSTANCES engines (default 1) with independent globals: instance 0 is doom_dev.o as built, instance k >= 1 is
// doom_dev_i<k>.o (doom/build.sh with DOOM_INSTANCES=N): the same code with every symbol prefixed i<k>_. Link all of them.
// The limit is KVM_DOOM_MAX_INSTANCES (64, include/kvm_doom_inst.inc generated by doom/gen_inst.py: `gen_inst.py 128 > ...` raises it).
#ifndef KVM_DOOM_INSTANCES
#define KVM_DOOM_INSTANCES 1
#endif
#define KVM_DOOM_CAT_(a, b) a##b
#define KVM_DOOM_CAT(a, b) KVM_DOOM_CAT_(a, b)
#define KVM_DOOM_SYM(k, name) KVM_DOOM_CAT(KVM_DOOM_PFX_##k, name)
#include "kvm_doom_inst.inc"
static_assert(KVM_DOOM_INSTANCES >= 1 && KVM_DOOM_INSTANCES <= KVM_DOOM_MAX_INSTANCES, "KVM_DOOM_INSTANCES must be 1..KVM_DOOM_MAX_INSTANCES");
// Dispatch on the instance id: KVM_DOOM_SWITCH(inst, M) runs the statement M(k) for k == inst; M uses KVM_DOOM_SYM(k, name).
// Instances beyond KVM_DOOM_INSTANCES are discarded by `if constexpr` (no reference, so their objects need not be linked); the caller
// bounds-checks `inst` first.

__device__ const unsigned char* g_kvm_doom_wad;   // uploaded by kvm_doom_host_init()
__device__ long g_kvm_doom_wad_len;

enum KvmDoomStatus { KVM_DOOM_OK = 0, KVM_DOOM_BAD_ORDER = 1, KVM_DOOM_NO_WAD = 2, KVM_DOOM_SMALL_BUF = 3, KVM_DOOM_BAD_INSTANCE = 4 };

// All threads of the CTA call; the return value is meaningful on thread 0 only (workers return KVM_DOOM_OK).
__device__ inline int kvm_doom_tick(int frame, const float* input, int n_input, float* state, int n_state, int inst = 0) {
  const int tid = threadIdx.x;
  if (tid >= KVM_DOOM_THREADS) return KVM_DOOM_OK;
  if (inst < 0 || inst >= KVM_DOOM_INSTANCES) return KVM_DOOM_BAD_INSTANCE;
#define KVM_DOOM_M_WORKER(k) KVM_DOOM_SYM(k, gpu_doom_worker)(tid);
  if (tid != 0) { KVM_DOOM_SWITCH(inst, KVM_DOOM_M_WORKER) return KVM_DOOM_OK; }
  int err = KVM_DOOM_OK;
  if (n_state < KVM_DOOM_ST_HEADER) err = KVM_DOOM_SMALL_BUF;
  else if (frame == 0 && g_kvm_doom_wad == nullptr) err = KVM_DOOM_NO_WAD;
  else if (frame != 0 && __float_as_int(__ldcg(state + KVM_DOOM_ST_TICS)) != frame) err = KVM_DOOM_BAD_ORDER;
#define KVM_DOOM_M_ABORT(k) KVM_DOOM_SYM(k, gpu_doom_abort_tic)();
#define KVM_DOOM_M_BOOT(k) KVM_DOOM_SYM(k, gpu_doom_boot)(g_kvm_doom_wad, g_kvm_doom_wad_len);
  if (err != KVM_DOOM_OK) { KVM_DOOM_SWITCH(inst, KVM_DOOM_M_ABORT) return err; }
  if (frame == 0) { KVM_DOOM_SWITCH(inst, KVM_DOOM_M_BOOT) }
  uint32_t in = KVM_DOOM_INPUT_SCRIPTED;
  if (input && n_input > frame + 1 && __float_as_uint(__ldcg(input)) == KVM_DOOM_INPUT_MAGIC) in = __float_as_uint(__ldcg(input + frame + 1));
  int32_t st[16] = {};
#define KVM_DOOM_M_TIC(k) KVM_DOOM_SYM(k, gpu_doom_tic)(in); KVM_DOOM_SYM(k, doom_state)(st);
  KVM_DOOM_SWITCH(inst, KVM_DOOM_M_TIC)
  for (int i = 0; i < 14; i++) state[i] = __int_as_float(st[i]);
  return KVM_DOOM_OK;
}

// ---- split tick: the same game tic as kvm_doom_tick, as a task graph  sim(f) -> draw(f, 0..T-1) -> post(f) -> present/status(f) -> sim(f+1).
//   sim:  thread 0 only. Game logic, BSP walk, sprite/plane setup, status bar; the 3D view is LOGGED (columns and spans of every wall,
//         plane, sprite) instead of drawn. A tick with no logged view (screen wipe, intermission) completes here.
//   draw: block-cooperative. Tile `tile` of `ntiles` draws the logged commands of its band of screen columns, in recording order.
//         Tiles of one frame are independent (disjoint pixels, read-only log), so they run on as many CTAs as the scheduler has idle.
//   post: thread 0 only. The display work after the view (HU messages, border, menu), then the frame is complete.
// The output is the frame the serial tick produces, pixel for pixel (doom/tests/run_split.sh compares against the CPU oracle).
__device__ inline int kvm_doom_sim(int frame, const float* input, int n_input, float* state, int n_state, int inst) {
  if (threadIdx.x != 0) return KVM_DOOM_OK;
  if (inst < 0 || inst >= KVM_DOOM_INSTANCES) return KVM_DOOM_BAD_INSTANCE;
  int err = KVM_DOOM_OK;
  if (n_state < KVM_DOOM_ST_HEADER) err = KVM_DOOM_SMALL_BUF;
  else if (frame == 0 && g_kvm_doom_wad == nullptr) err = KVM_DOOM_NO_WAD;
  else if (frame != 0 && __float_as_int(__ldcg(state + KVM_DOOM_ST_TICS)) != frame) err = KVM_DOOM_BAD_ORDER;
  int pending = 0;
#define KVM_DOOM_M_PEND(k) pending = KVM_DOOM_SYM(k, gpu_doom_pending)();
  if (err == KVM_DOOM_OK) { KVM_DOOM_SWITCH(inst, KVM_DOOM_M_PEND) if (pending) err = KVM_DOOM_BAD_ORDER; }   // the previous frame was not completed by its post task
  if (err != KVM_DOOM_OK) return err;
  if (frame == 0) { KVM_DOOM_SWITCH(inst, KVM_DOOM_M_BOOT) }
  uint32_t in = KVM_DOOM_INPUT_SCRIPTED;
  if (input && n_input > frame + 1 && __float_as_uint(__ldcg(input)) == KVM_DOOM_INPUT_MAGIC) in = __float_as_uint(__ldcg(input + frame + 1));
  int32_t st[16] = {};
#define KVM_DOOM_M_SIM(k) KVM_DOOM_SYM(k, gpu_doom_sim)(in); KVM_DOOM_SYM(k, doom_state)(st);
  KVM_DOOM_SWITCH(inst, KVM_DOOM_M_SIM)
  for (int i = 0; i < 14; i++) state[i] = __int_as_float(st[i]);
  return KVM_DOOM_OK;
}

// All threads of the CTA call (every thread returns the same status). Draws band `tile` of `ntiles` of tick `frame`'s logged view.
__device__ inline int kvm_doom_draw(int frame, int tile, int ntiles, int inst) {
  if (inst < 0 || inst >= KVM_DOOM_INSTANCES) return KVM_DOOM_BAD_INSTANCE;
  if (ntiles < 1 || ntiles > DOOM_W || tile < 0 || tile >= ntiles) return KVM_DOOM_SMALL_BUF;
  int pending = 0, tic = -1;
#define KVM_DOOM_M_LOGTIC(k) pending = KVM_DOOM_SYM(k, gpu_doom_pending)(); tic = KVM_DOOM_SYM(k, gpu_doom_log_tic)();
  KVM_DOOM_SWITCH(inst, KVM_DOOM_M_LOGTIC)
  if (!pending) return KVM_DOOM_OK;                       // the tick had no logged view (wipe / intermission): nothing to draw
  if (tic != frame + 1) return KVM_DOOM_BAD_ORDER;
#define KVM_DOOM_M_DRAW(k) KVM_DOOM_SYM(k, gpu_doom_draw)(tile, ntiles, threadIdx.x, blockDim.x);
  KVM_DOOM_SWITCH(inst, KVM_DOOM_M_DRAW)
  return KVM_DOOM_OK;
}

// All threads of the CTA call; thread 0 works. Finishes the tick's display after every tile of the frame is done.
__device__ inline int kvm_doom_post(int frame, int inst) {
  if (threadIdx.x != 0) return KVM_DOOM_OK;
  if (inst < 0 || inst >= KVM_DOOM_INSTANCES) return KVM_DOOM_BAD_INSTANCE;
  int pending = 0, tic = -1;
  KVM_DOOM_SWITCH(inst, KVM_DOOM_M_LOGTIC)
  if (pending && tic != frame + 1) return KVM_DOOM_BAD_ORDER;
#define KVM_DOOM_M_POST(k) KVM_DOOM_SYM(k, gpu_doom_post)();
  KVM_DOOM_SWITCH(inst, KVM_DOOM_M_POST)
  return KVM_DOOM_OK;
}

// All threads of the CTA call. Copies screen rows [row0, row0+rows) and, with row0 == 0, the palette.
// With state != nullptr it also checks that tick `frame` is the last one completed.
__device__ inline int kvm_doom_present(float* fb, int n_fb, int row0, int rows, const float* state, int n_state, int frame, int inst = 0) {
  if (inst < 0 || inst >= KVM_DOOM_INSTANCES) return KVM_DOOM_BAD_INSTANCE;
  if (n_fb < KVM_DOOM_FB_WORDS || row0 < 0 || rows < 0 || row0 + rows > DOOM_H) return KVM_DOOM_SMALL_BUF;
  if (state && frame >= 0 && __float_as_int(__ldcg(state + KVM_DOOM_ST_TICS)) != frame + 1) return KVM_DOOM_BAD_ORDER;
  const unsigned char* vb = nullptr; const uint32_t* pal = nullptr;
#define KVM_DOOM_M_VB(k) vb = KVM_DOOM_SYM(k, I_VideoBuffer); pal = KVM_DOOM_SYM(k, colors);
  KVM_DOOM_SWITCH(inst, KVM_DOOM_M_VB)
  { int pending = 0; KVM_DOOM_SWITCH(inst, KVM_DOOM_M_PEND) if (pending) return KVM_DOOM_BAD_ORDER; }   // a split tick's post task has not run yet
  unsigned char* out = reinterpret_cast<unsigned char*>(fb);
  for (int i = row0 * DOOM_W + threadIdx.x; i < (row0 + rows) * DOOM_W; i += blockDim.x) out[i] = __ldcg(vb + i);
  if (row0 == 0 && threadIdx.x < 256) fb[KVM_DOOM_PAL_WORD + threadIdx.x] = __uint_as_float(__ldcg(pal + threadIdx.x));
  return KVM_DOOM_OK;
}

// All threads of the CTA call (any blockDim <= 1024). Records the frame fingerprint of the current screen in state history slot `frame`.
__device__ inline int kvm_doom_status(int frame, float* state, int n_state, int inst = 0) {
  if (inst < 0 || inst >= KVM_DOOM_INSTANCES) return KVM_DOOM_BAD_INSTANCE;
  __shared__ uint32_t s_sum[32], s_xor[32];
  if (frame < 0 || n_state < KVM_DOOM_STATE_WORDS(frame + 1)) return KVM_DOOM_SMALL_BUF;
  if (__float_as_int(__ldcg(state + KVM_DOOM_ST_TICS)) != frame + 1) return KVM_DOOM_BAD_ORDER;
  const unsigned char* vb = nullptr; const uint32_t* pal = nullptr;
  KVM_DOOM_SWITCH(inst, KVM_DOOM_M_VB)
  { int pending = 0; KVM_DOOM_SWITCH(inst, KVM_DOOM_M_PEND) if (pending) return KVM_DOOM_BAD_ORDER; }
  uint32_t s = 0, x = 0;
  for (int i = threadIdx.x; i < DOOM_PIXELS + 256; i += blockDim.x) {
    const uint32_t v = i < DOOM_PIXELS ? __ldcg(vb + i) : __ldcg(pal + (i - DOOM_PIXELS));
    const uint32_t t = dh_term(i, v);
    s += t; x ^= t;
  }
  for (int o = 16; o; o >>= 1) { s += __shfl_down_sync(0xffffffffu, s, o); x ^= __shfl_down_sync(0xffffffffu, x, o); }
  if ((threadIdx.x & 31) == 0) { s_sum[threadIdx.x >> 5] = s; s_xor[threadIdx.x >> 5] = x; }
  __syncthreads();
  if (threadIdx.x == 0) {
    uint32_t ts = 0, tx = 0;
    for (int w = 0; w < (int)((blockDim.x + 31) >> 5); w++) { ts += s_sum[w]; tx ^= s_xor[w]; }
    state[KVM_DOOM_ST_HASH + KVM_DOOM_ST_REC * frame] = __uint_as_float(ts);
    state[KVM_DOOM_ST_HASH + KVM_DOOM_ST_REC * frame + 1] = __uint_as_float(tx);
  }
  if (threadIdx.x < 14) state[KVM_DOOM_ST_HASH + KVM_DOOM_ST_REC * frame + 2 + threadIdx.x] = state[threadIdx.x];
  __syncthreads();
  return KVM_DOOM_OK;
}

// ---------------------------------------------------------------- host helper
// Uploads the WAD and sets the stack limit. Call once before launching any kernel that runs doom_tick. Returns false (logged) on failure.
inline bool kvm_doom_host_init(const char* wad_path, int stack_bytes = KVM_DOOM_STACK_BYTES) {
  FILE* f = fopen(wad_path, "rb");
  if (!f) { fprintf(stderr, "[doom] cannot open WAD %s\n", wad_path); return false; }
  fseek(f, 0, SEEK_END); const long n = ftell(f); fseek(f, 0, SEEK_SET);
  std::vector<unsigned char> wad(n);
  const bool ok = fread(wad.data(), 1, n, f) == (size_t)n;
  fclose(f);
  if (!ok) { fprintf(stderr, "[doom] short read of %s\n", wad_path); return false; }
  unsigned char* d = nullptr;
  cudaError_t e = cudaMalloc(&d, n);
  if (e == cudaSuccess) e = cudaMemcpy(d, wad.data(), n, cudaMemcpyHostToDevice);
  if (e == cudaSuccess) e = cudaMemcpyToSymbol(g_kvm_doom_wad, &d, sizeof d);
  if (e == cudaSuccess) e = cudaMemcpyToSymbol(g_kvm_doom_wad_len, &n, sizeof n);
  if (e == cudaSuccess) e = cudaDeviceSetLimit(cudaLimitStackSize, stack_bytes);
  if (e != cudaSuccess) { fprintf(stderr, "[doom] host init failed: %s\n", cudaGetErrorString(e)); return false; }
  fprintf(stderr, "[doom] WAD %s (%ld bytes) uploaded, stack limit %d bytes/thread\n", wad_path, n, stack_bytes);
  return true;
}

