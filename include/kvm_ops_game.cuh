KVM_OP(doom_tick) {
  KvmView in = ARG_BUF(1), st = ARG_BUF(2);
  const int err = kvm_doom_tick(ARG_I32(0), in.p, in.rows * in.cols, st.p, st.rows * st.cols);
  if (err) c.fail(KVM_ERR_USER, 128, err);
}
