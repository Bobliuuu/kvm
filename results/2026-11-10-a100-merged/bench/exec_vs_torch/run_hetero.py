#!/usr/bin/env python3
"""Executor (`kvm_exec`) vs PyTorch on the panel's hetero row: R independent MLP runs of R different widths, N steps. No batched graph applies.

  python3 -I run_hetero.py WORK_DIR --exe ./kvm_exec --hiddens 48,56,64,72,80,88,96,104 --depth 2 --steps 200 --reps 5 --out OUT.json

Same bytes on both sides, one driver process, the shape of run_mlp.py: every variant is timed once per rep (CUDA events around N steps), then one
`kvm_exec` child runs the merged bundle (the kernel's own cudaEvent ms). Correctness first, a failure aborts before any timing:
  1. the narrowest and widest run's 3-step bundle within 1e-3 relative L2 of the CPU golden (generated by gen_mlp.py);
  2. the 3-step merged bundle (hetero_merge.py) bitwise equal, run by run, to each width's single-run 3-step bundle;
  3. the N-step merged bundle vs PyTorch eager from the same bytes, run by run: per-step loss and final weights, and the float64 reference;
  4. every other PyTorch variant (all runs) vs eager.
PyTorch variants (mlp_torch.py's bodies, the panel's "eager, graphs on 1 and R streams"):
  eager          the runs in a Python loop, per step
  seq_graph      one whole-step CUDA graph per run, replayed one after another on one stream
  multi_graph    one graph per run, each on its own stream (the GPU may overlap them); each captured on its own stream (mlp_torch.py's workspace note)
  seq_compile_graph / multi_compile_graph   the same with each run's forward+loss torch.compile'd first (a compiled graph per run)
  multi_compile_graph_whole     (bench_version 2) one whole-run compiled graph per run (all N steps of that run, its own step counter), the graphs replayed once on R streams
A batched graph cannot share runs of different shapes: it is not a variant here. Output keeps run_mlp.py's JSON, args.hetero = true, read by referee/panel.py.
"""
import argparse
import json
import os
import statistics
import subprocess
import sys
import time
import types
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
import torch  # noqa: E402
import mlp_torch as mt  # noqa: E402
from hetero_merge import merge  # noqa: E402
from run_mlp import COMPILE_TOL, LOSS_TOL, WEIGHT_TOL, exec_flags, fp64_losses, named_buffers, rel, run_exec  # noqa: E402
from torch_bench import is_capture_flake, with_capture_retries  # noqa: E402

DEFAULT_HIDDENS = '48,56,64,72,80,88,96,104'
VARIANTS = ('eager', 'seq_graph', 'multi_graph', 'seq_compile_graph', 'multi_compile_graph', 'multi_compile_graph_whole')


def gen_bundle(work: Path, hidden: int, steps: int, depth: int, tiling: str, golden: bool) -> Path:
    """One width's bundle at N steps (cached in WORK_DIR)."""
    out = work / f'h{hidden}_d{depth}_n{steps}'
    if not (out / 'bundle').exists():
        subprocess.run([sys.executable, '-I', str(ROOT / 'bench/exec_vs_torch/gen_mlp.py'), str(out), '--steps', str(steps), '--tiling', tiling,
                        '--hidden', str(hidden), '--depth', str(depth), *([] if golden else ['--no-golden'])], check=True, capture_output=True)
    return out


def bundle_tasks_per_step(wdir: Path, steps: int) -> int:
    return json.loads((wdir / 'bundle' / 'metadata.json').read_text())['task_count'] // steps


def gates_merge(work, exe, hiddens, depth, tiling):
    """Gates 1 and 2: the merge must change nothing a run computes."""
    singles = [gen_bundle(work, h, 3, depth, tiling, golden=h in (hiddens[0], hiddens[-1])) for h in hiddens]
    for h in (hiddens[0], hiddens[-1]):
        single = next(s for s, x in zip(singles, hiddens) if x == h)
        run_exec(exe, single / 'bundle', [], golden=True)
    merged = merge([s / 'bundle' for s in singles], work / 'merged_gate')
    tasks3 = sum(bundle_tasks_per_step(s, 3) * 3 for s in singles)
    _, merged_dump = run_exec(exe, work / 'merged_gate', exec_flags(tasks3), dump=True)
    offset = 0
    for s, h in zip(singles, hiddens):
        _, one = run_exec(exe, s / 'bundle', [], dump=True)
        for i in range(len(one)):
            if merged_dump[offset + i] != one[i]:
                raise SystemExit(f'GATE 2 FAILED: hidden {h}, buffer {i}: the merged run differs from the single run')
        offset += len(one)
    assert len(merged_dump) == offset, (len(merged_dump), offset)
    print(f'GATE 1+2 ok: h{hiddens[0]} and h{hiddens[-1]} within 1e-3 of the CPU golden; the {len(hiddens)}-run merged bundle bitwise equal, run by run, to each single run ({merged["task_count"]} tasks)', flush=True)


class OneRun(mt.Variant):
    """One run's parameters, log and step body; unlike mlp_torch.Variant its step counter is shared across runs (so one counter graph advances them all)."""

    def __init__(self, wl, ctr, loss_fn):       # (Variant's __init__ builds R identical runs of one wl; this builds one run of this wl)
        self.wl, self.r, self.name, self.batched = wl, 1, 'one', False
        self.sets = [[w.clone().requires_grad_() for w in wl.init]]
        self.ctr = ctr
        self.logs = [torch.zeros(wl.steps, 1, device=wl.dev)]
        self.loss_fn = loss_fn
        self.bodies = [self._body(self.sets[0], self.logs[0])]
        self.graphs = None
        self.streams = None


def own_copy(fn, k):
    """A copy of fn with its own code object. torch.compile keeps its cache on the code object, so 8 widths of one function would share it and hit the recompile limit: at the 9th
    specialization a compile falls back at capture time and invalidates the capture (Nov 9, 8 widths, `info.status != cudaStreamCaptureStatusInvalidated`)."""
    return types.FunctionType(fn.__code__.replace(co_name=f'{fn.__name__}_{k}'), fn.__globals__, f'{fn.__name__}_{k}')


class Composite:
    """R runs of different shapes advanced together. name is one of VARIANTS."""

    def __init__(self, workloads, name):
        self.name = name
        compiled, graphed = 'compile' in name, 'graph' in name
        self.multi = name.startswith('multi')
        self.whole = name.endswith('_whole')
        self.ctr = torch.zeros(1, dtype=torch.int64, device=workloads[0].dev)
        # (a whole-run graph advances its counter inside itself, so each run owns one: R streams must not race on one counter)
        ctrs = [torch.zeros(1, dtype=torch.int64, device=w.dev) for w in workloads] if self.whole else [self.ctr] * len(workloads)
        self.runs = [OneRun(w, c, torch.compile(own_copy(mt.single_loss, k), mode=mt.COMPILE_MODE, fullgraph=True) if compiled else mt.single_loss) for k, (w, c) in enumerate(zip(workloads, ctrs))]
        for run in self.runs:
            run.warm()
        self.graphs = None
        if self.whole:
            self.graphs = []
            self.capture_streams = [torch.cuda.Stream() for _ in self.runs]
            for run, stream in zip(self.runs, self.capture_streams):
                graph = torch.cuda.CUDAGraph()
                with torch.cuda.graph(graph, stream=stream, capture_error_mode=mt.CAPTURE_MODE):
                    for _ in range(run.wl.steps):
                        run.bodies[0]()
                        run.ctr.add_(1)
                self.graphs.append(graph)
        elif graphed:
            self.graphs = []
            for run in self.runs:
                run.capture(distinct_streams=self.multi)
                self.graphs.append(run.graphs[0])
            self.ctr_graph = torch.cuda.CUDAGraph()
            with torch.cuda.graph(self.ctr_graph, capture_error_mode=mt.CAPTURE_MODE):
                self.ctr.add_(1)
        self.streams = [torch.cuda.Stream() for _ in self.runs] if self.multi else None
        self.reset()
        self.steps = workloads[0].steps

    def reset(self):
        for run in self.runs:
            run.reset()

    def run(self, n):
        if self.graphs is None:
            for _ in range(n):
                for run in self.runs:
                    run.bodies[0]()
                self.ctr.add_(1)
            return
        if self.whole:
            if n != self.steps:
                raise ValueError(f'a whole-run graph replays exactly {self.steps} steps, not {n}')
            cur = torch.cuda.current_stream()
            for g, s in zip(self.graphs, self.streams):
                s.wait_stream(cur)
                with torch.cuda.stream(s):
                    g.replay()
            for s in self.streams:
                cur.wait_stream(s)
            return
        if self.multi:
            cur = torch.cuda.current_stream()
            for _ in range(n):
                for g, s in zip(self.graphs, self.streams):
                    s.wait_stream(cur)
                    with torch.cuda.stream(s):
                        g.replay()
                for s in self.streams:
                    cur.wait_stream(s)
                self.ctr_graph.replay()
            return
        for _ in range(n):
            for g in self.graphs:
                g.replay()
            self.ctr_graph.replay()

    def losses(self):
        """[run] -> the per-step losses of the last run()."""
        torch.cuda.synchronize()
        return [run.logs[0].view(-1).cpu().numpy().copy() for run in self.runs]

    def weights(self, k):
        return self.runs[k].weights()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('work')
    ap.add_argument('--exe', default='./kvm_exec')
    ap.add_argument('--hiddens', default=DEFAULT_HIDDENS)
    ap.add_argument('--depth', type=int, default=2)
    ap.add_argument('--steps', type=int, default=200)
    ap.add_argument('--reps', type=int, default=7)
    ap.add_argument('--tiling', default='a100')
    ap.add_argument('--skip', default='', help='comma list of torch variants to leave out')
    ap.add_argument('--out')
    a = ap.parse_args()
    work = Path(a.work)
    work.mkdir(parents=True, exist_ok=True)
    hiddens = [int(x) for x in a.hiddens.split(',')]
    r = len(hiddens)

    wdirs = [gen_bundle(work, h, a.steps, a.depth, a.tiling, golden=False) for h in hiddens]
    gates_merge(work, a.exe, hiddens, a.depth, a.tiling)
    merged_dir = work / f'merged_n{a.steps}'
    merge([w / 'bundle' for w in wdirs], merged_dir)
    tasks_step = [bundle_tasks_per_step(w, a.steps) for w in wdirs]
    flags = exec_flags(sum(tasks_step) * a.steps)

    mt.self_check_init()
    torch.backends.cuda.matmul.allow_tf32 = True
    torch.backends.cudnn.allow_tf32 = True
    props = torch.cuda.get_device_properties(0)
    env = dict(torch=torch.__version__, cuda=torch.version.cuda, gpu=props.name, sms=props.multi_processor_count)
    print('env', env, flush=True)
    workloads = [mt.Workload(w) for w in wdirs]

    # gate 3: the merged executor run vs PyTorch eager, run by run, and both vs float64
    skip = set(filter(None, a.skip.split(',')))
    names = [n for n in VARIANTS if n not in skip or n == 'eager']
    t_setup = time.time()
    eager = Composite(workloads, 'eager')
    eager.reset(); eager.run(a.steps)
    ref_loss = eager.losses()
    ref_w = [eager.weights(k) for k in range(r)]
    _, dump = run_exec(a.exe, merged_dir, flags, dump=True)
    idx = named_buffers(merged_dir)
    runs_gate, loss_rel, weight_rel = [], [], []
    fp64_ex, fp64_eager = [], []
    for k, (h, wl) in enumerate(zip(hiddens, workloads)):
        ex_loss = np.array([float(dump[idx[f'r{k}/loss.{s}']][0]) for s in range(a.steps)])
        ex_w = [np.array(dump[idx[f'r{k}/{name}']], dtype=np.float64).reshape(w.shape) for name, w in zip(wl.names, wl.init)]
        ref64 = fp64_losses(wl, a.steps)
        l_rel = float(np.max(np.abs(ex_loss - ref_loss[k]) / np.abs(ref_loss[k])))
        w_rel = {n: rel(e, w) for n, e, w in zip(wl.names, ex_w, ref_w[k])}
        d64_ex = float(np.max(np.abs(ex_loss - ref64) / np.abs(ref64)))
        d64_eager = float(np.max(np.abs(ref_loss[k] - ref64) / np.abs(ref64)))
        runs_gate.append(dict(hidden=h, exec_vs_eager_loss_max_rel=l_rel, exec_vs_eager_weight_rel_l2=w_rel, fp64_loss_max_rel=dict(executor=d64_ex, eager=d64_eager),
                              loss_first_last=[float(ref_loss[k][0]), float(ref_loss[k][-1])]))
        loss_rel.append(l_rel); weight_rel.append(max(w_rel.values())); fp64_ex.append(d64_ex); fp64_eager.append(d64_eager)
        print(f'GATE 3 h{h}: executor vs eager loss {l_rel:.2e}, weights {max(w_rel.values()):.2e}, loss {ref_loss[k][0]:.4f} -> {ref_loss[k][-1]:.4f}; vs float64: executor {d64_ex:.2e}, eager {d64_eager:.2e}', flush=True)
        if l_rel > LOSS_TOL or max(w_rel.values()) > WEIGHT_TOL:
            print('executor loss', ex_loss.tolist(), '\neager loss   ', ref_loss[k].tolist())
            raise SystemExit(f'GATE 3 FAILED: hidden {h}: the merged run does not match PyTorch within tolerance; no timing is reported')
    gate = dict(exec_vs_eager_loss_max_rel=max(loss_rel), exec_vs_eager_weight_rel_l2_max=max(weight_rel),
                fp64_loss_max_rel=dict(executor=max(fp64_ex), eager=max(fp64_eager)), runs=runs_gate)

    # gate 4: every PyTorch variant vs eager's trajectories, all runs
    variants = {'eager': (eager, 0.0)}
    skipped = []                                                        # whole-run variants a read could not capture; recorded in the output
    for name in list(names):
        if name == 'eager':
            continue
        try:
            v = with_capture_retries(lambda: Composite(workloads, name), name)
        except RuntimeError as exc:                                     # (torch.AcceleratorError is a RuntimeError)
            if not (name.endswith('_whole') and is_capture_flake(exc)):
                raise
            if int(os.environ.get('PANEL_STAGE_ATTEMPT', '1')) < int(os.environ.get('PANEL_STAGE_ATTEMPTS', '1')):
                raise       # (the whole-run graphs are x0.53 of this row's bar: a fresh process usually captures them, Nov 9; only the stage's last attempt falls back)
            print(f'{name}: SKIPPED, its whole-run CUDA graph could not be captured here ({type(exc).__name__}): {str(exc)[:200]}', flush=True)
            names.remove(name)
            skipped.append(dict(variant=name, error=str(exc)[:300]))
            continue
        v.reset(); v.run(a.steps)
        d = max(float(np.max(np.abs(l - ref) / np.abs(ref))) for l, ref in zip(v.losses(), ref_loss))
        tol = COMPILE_TOL if 'compile' in name else LOSS_TOL
        print(f'GATE 4 {name}: loss vs eager {d:.2e} (tol {tol:.0e})', flush=True)
        if d > tol:
            raise SystemExit(f'GATE 4 FAILED: {name} loss differs from eager by {d:.2e}')
        variants[name] = (v, d)

    t_us = {n: [] for n in names}
    t_us['executor'] = []
    e0, e1 = torch.cuda.Event(enable_timing=True), torch.cuda.Event(enable_timing=True)
    from torch_bench import exec_warm_args, gpu_warm
    warm_args = exec_warm_args(a.exe)
    for rep in range(a.reps):
        for n in names:
            v = variants[n][0]
            gpu_warm()                                                   # (bench_version 3: every timed window starts at the same clock state)
            v.reset(); torch.cuda.synchronize()
            e0.record(); v.run(a.steps); e1.record(); torch.cuda.synchronize()
            t_us[n].append(e0.elapsed_time(e1) * 1e3 / a.steps)
        gpu_warm()                                                       # (the executor child starts within the clock's hold time)
        ms, _ = run_exec(a.exe, merged_dir, [*flags, *warm_args])
        t_us['executor'].append(ms * 1e3 / a.steps)
    row = dict(hetero=True, hiddens=hiddens, depth=a.depth, steps=a.steps, runs=r, tasks_per_step_per_run=tasks_step, reps=a.reps,
               loss_max_rel_vs_eager={n: variants[n][1] for n in names}, setup_s=round(time.time() - t_setup, 1),
               us_per_step={n: dict(best=min(v), median=statistics.median(v), worst=max(v), all=[round(x, 1) for x in v]) for n, v in t_us.items()})
    print(json.dumps(dict(runs=r, steps=a.steps) | {n: round(d['best'], 1) for n, d in row['us_per_step'].items()}), flush=True)
    ex = row['us_per_step']['executor']['best']
    print('best-of-%d us per step (all %d runs advance one step), and ratio variant / executor (>1: executor faster):' % (a.reps, r))
    for n, d in row['us_per_step'].items():
        print(f'  {n:22s} {d["best"]:10.1f}  (median {d["median"]:.1f}, worst {d["worst"]:.1f})  {d["best"] / ex:6.2f}x')
    out = dict(env=env, gate=gate, args=vars(a) | {'hetero': True, 'hidden': 0}, rows=[row], skipped_variants=skipped, exec_warm_args=warm_args)
    if a.out:
        Path(a.out).write_text(json.dumps(out, indent=1))


if __name__ == '__main__':
    main()
